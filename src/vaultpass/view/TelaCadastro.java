    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
        JPanel painelInserir = new JPanel(new GridLayout(3, 2, 8, 8));
    
        JTextField txtRotuloPopup = new JTextField(15);
        JTextField txtUsuarioPopup = new JTextField(15);
        JPasswordField txtSenhaPopup = new JPasswordField(15);
    
        painelInserir.add(new JLabel("Rótulo (ex: Banco, E-mail):"));
        painelInserir.add(txtRotuloPopup);
        painelInserir.add(new JLabel("Usuário / Login:"));
        painelInserir.add(txtUsuarioPopup);
        painelInserir.add(new JLabel("Senha:"));
        painelInserir.add(txtSenhaPopup);

        int resultado = JOptionPane.showConfirmDialog(
            this, painelInserir, "VaultPass - Nova Credencial", 
            JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE
        );

        if (resultado == JOptionPane.OK_OPTION) {
            String rotulo = txtRotuloPopup.getText();
            String usuario = txtUsuarioPopup.getText();
            String senha = new String(txtSenhaPopup.getPassword());

            if (rotulo.isEmpty() || usuario.isEmpty() || senha.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos!", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Credencial novaCredencial = new Credencial();
            novaCredencial.definirRotulo(rotulo);
            novaCredencial.definirUsuario(usuario);
            novaCredencial.definirSenha(senha);

            CredencialDAO dao = new CredencialDAO();
            if (dao.inserir(novaCredencial)) {
                JOptionPane.showMessageDialog(this, "Credencial guardada com sucesso no MySQL!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao guardar na base de dados.", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jMenuItem1ActionPerformed

    private void jMenuItem2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem2ActionPerformed
        CredencialDAO dao = new CredencialDAO();
        List<Credencial> lista = dao.listar();

        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ainda não existem credenciais guardadas no cofre.", "Cofre Vazio", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        StringBuilder sb = new StringBuilder();
        for (Credencial c : lista) {
            sb.append("Rótulo: ").append(c.obterRotulo())
              .append("\nUsuário: ").append(c.obterUsuario())
              .append("\nSenha: ").append(c.obterSenha())
              .append("\n-----------------------------------\n");
        }

        JTextArea textArea = new JTextArea(sb.toString(), 12, 30);
        textArea.setEditable(false);
        JScrollPane scrollPane = new JScrollPane(textArea);

        JOptionPane.showMessageDialog(this, scrollPane, "VaultPass - Credenciais Guardadas", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jMenuItem2ActionPerformed

